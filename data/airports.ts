const BY_CODE = new Map<string, Airport>();

export const AIRPORTS: Airport[] = RAW.map(([code, name, city, country, latitude, longitude]) => {
  const airport: Airport = { code, name, city, country, latitude, longitude };
  BY_CODE.set(code, airport);
  return airport;
});

export function getAirport(code: string | null | undefined): Airport | null {
  if (!code) return null;
  return BY_CODE.get(code.trim().toUpperCase()) ?? null;
}

const stripAccents = (s: string): string =>
  s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase();

// Search by IATA code, city, airport name or country code. Best matches first.
export function searchAirports(query: string, limit = 30): Airport[] {
  const q = stripAccents(query.trim());
  if (!q) return AIRPORTS.slice(0, limit);

  const scored: { airport: Airport; score: number }[] = [];
  for (const airport of AIRPORTS) {
    const code = airport.code.toLowerCase();
    const city = stripAccents(airport.city);
    const name = stripAccents(airport.name);
    let score = 0;
    if (code === q) score = 100;
    else if (city === q) score = 90;
    else if (code.startsWith(q)) score = 80;
    else if (city.startsWith(q)) score = 70;
    else if (name.startsWith(q)) score = 60;
    else if (city.includes(q)) score = 50;
    else if (name.includes(q)) score = 40;
    if (score > 0) scored.push({ airport, score });
  }
  scored.sort((a, b) => b.score - a.score || a.airport.city.localeCompare(b.airport.city));
  return scored.slice(0, limit).map(s => s.airport);
}

export function airportLabel(a: Airport): string {
  return `${a.city} (${a.code})`;
}
